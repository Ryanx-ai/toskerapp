import assert from "node:assert/strict";
import { run, ev, until, button } from "./browser-fp2.mjs";
const a="ms72-a",b="ms72-b",origin="http://localhost:3000",room="/room/ms722-frame-qa";
const id=n=>`f7220000-2026-4000-8000-${n.toString(16).padStart(12,"0")}`;
const pins="[...document.querySelectorAll('.messenger-sidebar .sidebar-pin-row.is-pinned')].map(e=>e.dataset.pinId)";
const children="[...document.querySelectorAll('.messenger-sidebar [data-subroom-id]')].map(e=>e.dataset.subroomId).filter(id=>id.startsWith('f7220000'))";
const menu="document.querySelector('.interaction-popover:popover-open')";
async function open(s,path=room) { await run(s,"open",origin+path); await until(s,"!!document.querySelector('.composer textarea')","Chat ready"); }
for(const s of [a,b]) { await run(s,"set","viewport","1440","900"); await open(s); }
const beforeA=await ev(a,pins),beforeB=await ev(b,pins);
assert(!beforeA.includes(id(11))&&!beforeA.includes(id(12)),"Only fresh fixture pins are safe to exercise");
assert.deepEqual(await ev(a,children),[id(3),id(4)]);
await button(a,"Organize your Sandbox");
assert(await ev(a,`${menu}.textContent.includes('Your Profile')&&!/Pin to top|Mute|Leave Room/.test(${menu}.textContent)`));
await run(a,"press","Escape");
assert.equal(await ev(a,"document.activeElement?.getAttribute('aria-label')"),"Organize your Sandbox");
for(const name of ["MS7.2 Frame QA","MS7.2 Second QA"]) { await button(a,`Organize ${name}`); await button(a,"Pin to top"); await until(a,`${pins}.length===${beforeA.length+(name.includes("Second")?2:1)}`,"pin saved"); }
await button(a,"Organize MS7.2 Second QA"); await button(a,"Move earlier");
await until(a,`JSON.stringify(${pins})===${JSON.stringify(JSON.stringify([...beforeA,id(12),id(11)]))}`,"private pin order");
await open(a); assert.deepEqual(await ev(a,pins),[...beforeA,id(12),id(11)]);
await open(b); assert.deepEqual(await ev(b,pins),beforeB);
for(const name of ["MS7.2 Frame QA","MS7.2 Second QA"]) { await button(a,`Organize ${name}`); await button(a,"Unpin"); await until(a,`${pins}.length===${beforeA.length+(name.includes("Second")?0:1)}`,"fixture unpinned"); }
assert.deepEqual(await ev(a,pins),beforeA);
console.log("PASS Sandbox scope; private pin/move/reload; B unchanged; original A order restored");
await button(a,"Actions for MS7.2 Beta"); await button(a,"Move earlier");
await until(a,`JSON.stringify(${children})===${JSON.stringify(JSON.stringify([id(4),id(3)]))}`,"shared child order");
await open(b); assert.deepEqual(await ev(b,children),[id(4),id(3)]);
await button(b,"Actions for MS7.2 Alpha");
assert(await ev(b,`!/Move earlier|Move later|Pin to top|Leave Room/.test(${menu}.textContent)&&${menu}.textContent.includes('Parent Room Settings')`));
await run(b,"press","Escape");
await button(a,"Actions for MS7.2 Alpha"); await button(a,"Move earlier");
await until(a,`JSON.stringify(${children})===${JSON.stringify(JSON.stringify([id(3),id(4)]))}`,"child order restored");
await button(a,"Organize MS7.2 Frame QA"); await button(a,"Mute");
await until(a,`!${menu}`,"mute finished");
await button(a,"Actions for MS7.2 Alpha");
await until(a,`[...${menu}.querySelectorAll('button')].some(e=>e.textContent==='Muted by Room'&&e.disabled)`,"inherited mute");
await run(a,"press","Escape");
await button(b,"Organize MS7.2 Frame QA"); assert(await ev(b,`[...${menu}.querySelectorAll('button')].some(e=>e.textContent==='Mute'&&!e.disabled)`));
await run(b,"press","Escape");
await button(a,"Organize MS7.2 Frame QA"); await button(a,"Unmute");
await until(a,`!${menu}`,"unmute finished");
await button(a,"Organize MS7.2 Frame QA"); await button(a,"Mark Chat unread");
await until(a,"location.pathname==='/app'","selected Chat exits without immediate reread");
await open(a);
console.log("PASS owner shared ordering/B member controls; child inherited mute; viewer-only mute; selected mark-unread navigation; fixture order/mute restored");
await button(a,"Organize MS7.2 Frame QA"); await button(a,"Room Settings");
await until(a,"!!document.querySelector('.scoped-settings-form input')","sidebar Room Settings");
await button(a,"Close Room Settings");
await button(a,"Organize MS7.2 Frame QA"); await button(a,"Invite");
await until(a,"!!document.querySelector('.fp2-invite-panel')","sidebar Invite");
await run(a,"press","Escape");
await open(b,"/room/ms722-second-qa");
await button(b,"Organize MS7.2 Second QA"); await button(b,"Leave Room");
await until(b,"!!document.querySelector('.room-confirmation')","member confirmation");
await button(b,"Cancel"); await button(b,"Close Room Settings");
await button(a,"Collapse sidebar");
assert(await ev(a,"!!document.querySelector('button[aria-label=\"Expand sidebar\"]')"));
await button(a,"Expand sidebar");
assert(await ev(a,"![...document.querySelectorAll('.messenger-sidebar time')].some(e=>e.textContent==='Now')"));
console.log("PASS sidebar Room Settings/Invite/member Leave confirmation-cancel and explicit sidebar recovery; no fake Now labels");
