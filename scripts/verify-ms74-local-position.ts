import assert from "node:assert/strict";
import { acceptLocalFix, LOCAL_POSITION_LIFETIME, validLocalFix } from "../src/lib/maps/local-position";
const first = { latitude: 1.28, longitude: 103.85, accuracy: 10 };
const second = { latitude: 1.29, longitude: 103.86, accuracy: 15 };
const initial = acceptLocalFix(null, first, 1000)!;
assert.equal(initial.origin, first);
assert.equal(initial.current, first);
assert.equal(initial.expiresAt, 1000 + LOCAL_POSITION_LIFETIME);
const refreshed = acceptLocalFix(initial, second, 5000)!;
assert.equal(refreshed.origin, first);
assert.equal(refreshed.current, second);
assert.equal(refreshed.expiresAt, initial.expiresAt);
assert.equal(acceptLocalFix(refreshed, { ...second, latitude: NaN }, 6000), refreshed);
assert.equal(validLocalFix({ ...first, accuracy: -1 }), false);
assert.equal(validLocalFix({ ...first, longitude: 181 }), false);
const expired = acceptLocalFix(refreshed, second, initial.expiresAt)!;
assert.equal(expired.origin, second);
assert.equal(expired.expiresAt, initial.expiresAt + LOCAL_POSITION_LIFETIME);
assert.equal(acceptLocalFix(null, second, 7000)?.origin, second);
console.log(JSON.stringify({ gate: "FP2A fixed private origin / refreshed marker / absolute expiry", result: "pass", providerCalls: 0 }));
